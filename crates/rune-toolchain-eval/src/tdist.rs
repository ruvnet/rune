/// 0.975 quantile of Student's t with `df` degrees of freedom.
/// Beyond the table: normal quantile with the first Cornish-Fisher correction.
pub fn t975(df: usize) -> f64 {
    match df {
        0 => f64::INFINITY,
        1..=200 => T975[df - 1],
        _ => {
            let z = 1.959_964;
            z + (z * z * z + z) / (4.0 * df as f64)
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_values() {
        assert!((t975(1) - 12.7062).abs() < 1e-4);
        assert!((t975(10) - 2.2281).abs() < 1e-4);
        assert!((t975(29) - 2.0452).abs() < 1e-4);
        assert!((t975(200) - 1.9719).abs() < 1e-4);
        assert!((t975(100_000) - 1.96).abs() < 1e-3);
    }

    #[test]
    fn monotone_decreasing() {
        for df in 1..400 {
            assert!(t975(df) >= t975(df + 1), "df {df}");
        }
    }
}
